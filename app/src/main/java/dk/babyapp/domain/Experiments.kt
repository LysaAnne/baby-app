package dk.babyapp.domain

/**
 * Eksperimenter under Udvikling: small, safe versions of classic developmental-psychology studies that parents can
 * try at home, ordered by age and ticked off when done. Written in the app's own words in November 2026 from the
 * published studies (researchers and years are named so they can be looked up); not taken from any book.
 */
data class HomeExperiment(
    val number: Int,
    val title: String,
    val ageLabel: String,
    val fromMonths: Double,
    val toMonths: Double,
    /** "Hvad undersøger det?" */
    val idea: String,
    /** "Du skal bruge" */
    val materials: List<String>,
    /** "Sådan gør du", numbered. */
    val steps: List<String>,
    /** "Det kan du kigge efter" */
    val lookFor: List<String>,
    /** "Forskningen bag": the original study and what it showed. */
    val research: String,
    /** "Pas på": safety, shown when not blank. */
    val safety: String = "",
) {
    val key get() = "exp-$number"
    fun isActive(months: Double) = months >= fromMonths && months <= toMonths
}

