package dk.babyapp.domain

/**
 * Psykologisk udvikling: evidence-based phenomena in developmental psychology with their typical ages, the
 * experiments behind them and the methodological reservations. Built from the user's own overview document
 * (written with ChatGPT and pasted into the project chat on 30 October 2026); ages are typical intervals.
 */
enum class PsychArea(val label: String) {
    Cognition("Kognitiv udvikling"),
    SocialCognition("Social kognition og Theory of Mind"),
    Self("Selvudvikling og selvbevidsthed"),
    Emotion("Emotionel og relationel udvikling"),
    Executive("Eksekutive funktioner og selvkontrol"),
    Moral("Moral, retfærdighed og social forståelse"),
    Language("Sprog og kommunikation"),
    Perspective("Perspektivtagning og social identitet"),
    Adolescence("Ungdomsalderen"),
}

